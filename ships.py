# Сопоставление с причалами
# ---------------------------------------------------------------------------
# ---------------------------------------------------------------------------
# Отсев стационарных объектов
# ---------------------------------------------------------------------------
# Персидский залив усеян буровыми платформами, выносными причалами и
# буями. На снимке они выглядят точно как суда: яркое компактное пятно
# на тёмной воде. Без отсева они попадали бы в счёт КАЖДЫЙ раз, завышая
# цифру и создавая ложное ощущение стабильного трафика.
#
# Отличить их можно без всякого распознавания: судно движется, платформа
# стоит. Если объект виден на том же месте в несколько разных дат —
# это не судно.
#
# Приём бесплатный и не требует ни нейросетей, ни справочников: нужна
# только история наблюдений, которая и так копится.

def _metres_between(lat1, lon1, lat2, lon2):
    """Расстояние между точками в метрах. Для сотен метров хватает с избытком."""
    import math
    dlat = (lat1 - lat2) * 110540.0
    dlon = (lon1 - lon2) * 111320.0 * math.cos(math.radians((lat1 + lat2) / 2))
    return math.hypot(dlat, dlon)


def load_history(path):
    """Читает историю обнаружений. Пустая история — не ошибка."""
    if not os.path.exists(path):
        return []
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (json.JSONDecodeError, OSError):
        return []


def save_history(path, history, keep_days=120, max_points=20000):
    """
    Сохраняет историю, обрезая слишком старое.

    keep_days — глубина памяти. Платформа стоит годами, так что
    четырёх месяцев с запасом хватает, чтобы её опознать, а старее
    хранить незачем: файл рос бы без конца.
    """
    import datetime as dt
    cutoff = (dt.date.today() - dt.timedelta(days=keep_days)).isoformat()
    kept = [h for h in history if h.get("date", "") >= cutoff][-max_points:]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(kept, fh, ensure_ascii=False)
    return kept


def split_fixed(vessels, history, current_date,
                radius_m=180, min_other_dates=2):
    """
    Делит находки на движущиеся суда и стационарные объекты.

    Объект считается стационарным, если рядом с ним (в пределах
    radius_m) уже видели что-то в min_other_dates других дат.

    radius_m 180 метров взят не случайно: при 30 метрах на пиксель
    в проливе это шесть пикселей — достаточно, чтобы простить
    неточность привязки снимка, и мало, чтобы не склеить соседние
    суда на якорной стоянке.

    Возвращает (суда, стационарные объекты).
    """
    moving, fixed = [], []
    for v in vessels:
        dates = set()
        for h in history:
            if h.get("date") == current_date:
                continue        # сам себя не подтверждает
            if _metres_between(v["lat"], v["lon"],
                               h["lat"], h["lon"]) <= radius_m:
                dates.add(h.get("date"))
                if len(dates) >= min_other_dates:
                    break
        if len(dates) >= min_other_dates:
            v = dict(v)
            v["seen_dates"] = len(dates)
            fixed.append(v)
        else:
            moving.append(v)
    return moving, fixed


def remember(history, vessels, date):
    """Добавляет находки текущего дня в историю."""
    for v in vessels:
        history.append({"date": date,
                        "lat": round(v["lat"], 5),
                        "lon": round(v["lon"], 5)})
    return history


def assign_to_berths(vessels, berths):
    """
    Раскладывает найденные суда по причалам.

    Нужно, когда AIS не работает: по снимку видно, что судно стоит у
    причала СПГ, даже если транспондер выключен. Тип груза при этом
    берётся из типа причала, а не из судна.
    """
    out = {}
    for v in vessels:
        for name, meta in berths.items():
            if meta.get("kind") in ("anchorage",):
                continue
            b = meta["bbox"]
            if b[0] <= v["lon"] <= b[2] and b[1] <= v["lat"] <= b[3]:
                out.setdefault(name, {"kind": meta["kind"],
                                      "venture": meta.get("venture", ""),
                                      "vessels": []})
                out[name]["vessels"].append(v)
                break
    return out
