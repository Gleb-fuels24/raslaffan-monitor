def detect(bands, bbox, px_size_m=None, nir_threshold=0.12,
           min_len_m=80, max_len_m=500, adaptive=True):
    """
    Находит суда в зоне и оценивает их длину.

    bands       — каналы снимка, как их отдаёт analyze._read
    bbox        — рамка зоны [запад, юг, восток, север]
    px_size_m   — размер пикселя в метрах; если не задан, считается из bbox
    min_len_m   — суда короче этого не считаем (шум, буи, мелкие катера)
    max_len_m   — длиннее этого не бывает: такое пятно почти наверняка
                  причал, мель или облако, а не судно
    adaptive    — считать порог по окрестности (устойчиво к солнечному
                  блику и мути) или брать постоянный nir_threshold

    Возвращает список судов и сводку.
    """
    valid = bands["mask"] > 0
    nir = bands["nir"]
    h, w = nir.shape

    if px_size_m is None:
        px_size_m = _pixel_size_m(bbox, w, h)

    # Суша тоже ярко светит в ближнем ИК, поэтому отсекаем её:
    # у воды коротковолновый ИК почти нулевой, у суши заметный.
    water_like = bands["swir1"] < 0.12

    if adaptive:
        # Порог считается по окрестности: устойчив к блику и мути.
        bright = adaptive_mask(nir, valid & water_like, px_size_m,
                               floor=nir_threshold * 0.5)
    else:
        bright = (nir > nir_threshold) & valid & water_like

    if bright.sum() == 0:
        return {"vessels": [], "count": 0, "px_size_m": round(px_size_m, 1),
                "large_count": 0, "total_length_m": 0}

    labels, n = label_blobs(bright)

    vessels = []
    for i in range(1, n + 1):
        ys, xs = np.nonzero(labels == i)
        if len(ys) < 2:
            continue
        # Габариты пятна. Длина судна — большая сторона.
        dy = (ys.max() - ys.min() + 1) * px_size_m
        dx = (xs.max() - xs.min() + 1) * px_size_m
        length = max(dy, dx)
        beam = min(dy, dx)

        if length < min_len_m or length > max_len_m:
            continue
        # У судна корпус вытянутый. Почти квадратное пятно — скорее
        # всего не судно, а платформа, мель или кусок причала.
        if beam > 0 and length / beam < 1.6:
            continue

        lat = bbox[3] - (ys.mean() / h) * (bbox[3] - bbox[1])
        lon = bbox[0] + (xs.mean() / w) * (bbox[2] - bbox[0])

        vessels.append({
            "length_m": int(round(length / 10) * 10),
            "beam_m": int(round(beam)),
            "pixels": int(len(ys)),
            "lat": round(float(lat), 5),
            "lon": round(float(lon), 5),
            "size_class": _size_class(length),
        })

    vessels.sort(key=lambda v: -v["length_m"])
    large = [v for v in vessels if v["length_m"] >= 200]

    # Ниже какой длины считать бессмысленно. Чтобы вытянутое пятно
    # уверенно опознавалось как корпус, нужно хотя бы четыре пикселя
    # в длину. Всё, что короче, тонет в шуме.
    reliable = round(px_size_m * 4)

    return {
        "vessels": vessels,
        "count": len(vessels),
        "large_count": len(large),
        "total_length_m": sum(v["length_m"] for v in vessels),
        "px_size_m": round(px_size_m, 1),
        "reliable_min_len_m": reliable,
        # Порог меньше предела разрешения — значит часть судов
        # не будет найдена, и об этом надо сказать вслух.
        "threshold_too_low": min_len_m < reliable,
    }


def _size_class(length_m):
    """
    Грубая разбивка по размеру. Это НЕ тип судна: по снимку тип не
    определяется. Только порядок величины для понимания картины.
    """
    if length_m >= 300:
        return "очень крупное (300 м+)"
    if length_m >= 200:
        return "крупное (200-300 м)"
    if length_m >= 120:
        return "среднее (120-200 м)"
    return "небольшое (до 120 м)"


def _pixel_size_m(bbox, width_px, height_px):
    """
    Сколько метров в одном пикселе.

    Считается по ОБЕИМ осям, а не только по широте. Раньше бралась
    только широта, и если картинку запросили не в пропорциях зоны,
    горизонтальный масштаб молча расходился с вертикальным: судно,
    лежащее поперёк кадра, измерялось не тем числом метров на пиксель.
    Ошибка тихая — она не ломает программу, а просто делает длину
    неверной, из-за чего крупное судно может не пройти порог.

    Теперь при расхождении больше чем на 5% печатается
    предупреждение, а размер берётся средний.
    """
    import math
    w, s, e, n = bbox
    sx = ((e - w) * 111320.0 * math.cos(math.radians((s + n) / 2.0))
          / max(width_px, 1))
    sy = ((n - s) * 110540.0) / max(height_px, 1)

    if min(sx, sy) > 0 and abs(sx - sy) / min(sx, sy) > 0.05:
        print(f"  [!] пиксель неквадратный: {sx:.1f} м по горизонтали и "
              f"{sy:.1f} по вертикали. Длины судов будут неточными — "
              f"картинку надо запрашивать в пропорциях зоны.")
    return (sx + sy) / 2.0


